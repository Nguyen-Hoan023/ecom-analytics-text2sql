"""Stage the repository's runtime code inside Astro's Docker build context.

Run from any directory with:
    uv run --active python orchestration/scripts/prepare_runtime.py

Only allowlisted source files are copied. Secrets, local profiles, DuckDB files,
dbt artifacts, Python environments, and logs are deliberately excluded.
"""

from __future__ import annotations

import os
import shutil
import sys
import uuid
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
ASTRO_ROOT = REPO_ROOT / "orchestration"
INCLUDE_ROOT = ASTRO_ROOT / "include"
RUNTIME_ROOT = INCLUDE_ROOT / "runtime"
PROFILE_TEMPLATE = REPO_ROOT / "ecom_analytics" / "profiles.yml.example"
MARKER_NAME = ".generated-by-prepare_runtime"
MARKER_CONTENT = "Generated by orchestration/scripts/prepare_runtime.py. Do not edit.\n"

IGNORED_DIRS = {
    ".astro",
    ".cache",
    ".dlt",
    ".git",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".venv",
    "__pycache__",
    "dbt_internal_packages",
    "dbt_packages",
    "logs",
    "target",
    "venv",
}
IGNORED_FILES = {
    ".env",
    "profiles.yml",
    ".user.yml",
    "airflow.db",
    "warehouse.duckdb",
}


def _copy_allowlisted_tree(
    source: Path,
    destination: Path,
    allowed_suffixes: frozenset[str],
) -> int:
    """Copy regular files from a source tree without following symlinks."""
    if not source.is_dir():
        raise FileNotFoundError(f"Required project directory is missing: {source}")

    copied = 0
    for current, directory_names, file_names in os.walk(source, followlinks=False):
        current_path = Path(current)
        directory_names[:] = sorted(
            name
            for name in directory_names
            if name not in IGNORED_DIRS
            and not (current_path / name).is_symlink()
        )

        for file_name in sorted(file_names):
            source_file = current_path / file_name
            if source_file.is_symlink() or file_name in IGNORED_FILES:
                continue
            if source_file.suffix.casefold() not in allowed_suffixes:
                continue

            relative_path = source_file.relative_to(source)
            target_file = destination / relative_path
            target_file.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_file, target_file)
            copied += 1

    return copied


def _validate_staging(staging_root: Path) -> dict[str, int]:
    """Fail before replacing an existing stage if required inputs are absent."""
    required_files = (
        staging_root / "ingestion" / "run_pipeline.py",
        staging_root / "ingestion" / "check_source_connection.py",
        staging_root / "text2sql" / "evaluation" / "run_baselines.py",
        staging_root / "text2sql" / "evaluation" / "golden_set_v1.yml",
        staging_root / "ecom_analytics" / "dbt_project.yml",
        staging_root / "ecom_analytics" / "profiles.yml",
    )
    missing = [str(path.relative_to(staging_root)) for path in required_files if not path.is_file()]
    if missing:
        raise RuntimeError(f"Staged runtime is missing required files: {', '.join(missing)}")

    forbidden_staged_files = (
        list(staging_root.rglob("*.duckdb"))
        + list(staging_root.rglob(".env"))
        + list(staging_root.rglob(".user.yml"))
    )
    if forbidden_staged_files:
        relative_paths = sorted(
            path.relative_to(staging_root).as_posix()
            for path in forbidden_staged_files
        )
        raise RuntimeError(
            "Refusing to stage local-only files: " + ", ".join(relative_paths)
        )

    return {
        package: sum(1 for path in (staging_root / package).rglob("*") if path.is_file())
        for package in ("ingestion", "text2sql", "ecom_analytics")
    }


def _replace_generated_stage(staging_root: Path) -> None:
    """Replace only a prior stage carrying our marker; preserve other user data."""
    backup_root: Path | None = None
    if RUNTIME_ROOT.exists():
        marker = RUNTIME_ROOT / MARKER_NAME
        if not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER_CONTENT:
            raise RuntimeError(
                f"Refusing to replace {RUNTIME_ROOT}: it is not marked as generated. "
                "Move or inspect that directory manually before retrying."
            )
        backup_root = INCLUDE_ROOT / f".runtime-backup-{uuid.uuid4().hex}"
        RUNTIME_ROOT.rename(backup_root)

    try:
        staging_root.rename(RUNTIME_ROOT)
    except Exception:
        if backup_root is not None and backup_root.exists() and not RUNTIME_ROOT.exists():
            backup_root.rename(RUNTIME_ROOT)
        raise
    else:
        if backup_root is not None:
            shutil.rmtree(backup_root)


def main() -> int:
    INCLUDE_ROOT.mkdir(parents=True, exist_ok=True)
    staging_root = INCLUDE_ROOT / f".runtime-staging-{uuid.uuid4().hex}"
    staging_root.mkdir()
    (staging_root / MARKER_NAME).write_text(MARKER_CONTENT, encoding="utf-8")

    try:
        counts = {
            "ingestion": _copy_allowlisted_tree(
                REPO_ROOT / "ingestion",
                staging_root / "ingestion",
                frozenset({".py"}),
            ),
            "text2sql": _copy_allowlisted_tree(
                REPO_ROOT / "text2sql",
                staging_root / "text2sql",
                frozenset({".py", ".yml", ".yaml"}),
            ),
            "ecom_analytics": _copy_allowlisted_tree(
                REPO_ROOT / "ecom_analytics",
                staging_root / "ecom_analytics",
                frozenset({".sql", ".yml", ".yaml", ".csv"}),
            ),
        }

        if not PROFILE_TEMPLATE.is_file():
            raise FileNotFoundError(f"Safe dbt profile template is missing: {PROFILE_TEMPLATE}")
        shutil.copy2(
            PROFILE_TEMPLATE,
            staging_root / "ecom_analytics" / "profiles.yml",
        )
        (staging_root / "ecom_analytics" / "target").mkdir(exist_ok=True)
        (staging_root / "ecom_analytics" / "logs").mkdir(exist_ok=True)

        counts = _validate_staging(staging_root)
        _replace_generated_stage(staging_root)
    except Exception:
        # Only remove this uniquely named temp directory, which this invocation created.
        if staging_root.exists() and (staging_root / MARKER_NAME).is_file():
            shutil.rmtree(staging_root)
        raise

    print(f"Astro runtime source staged at: {RUNTIME_ROOT}")
    for package, count in counts.items():
        print(f"{package}: {count} allowlisted files")
    print("Local profiles.yml was generated from profiles.yml.example; no secrets or warehouse data copied.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"Runtime staging failed ({type(exc).__name__}): {exc}", file=sys.stderr)
        raise SystemExit(1)
