"""Check that dbt's Gold graph matches the Text-to-SQL semantic catalog."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from text2sql.catalog import CatalogConfigError, SemanticCatalog, load_config


class DbtCatalogContractError(ValueError):
    """Raised when dbt's Gold relations drift from the semantic catalog."""


def validate_dbt_manifest(
    manifest: Mapping[str, Any], catalog: SemanticCatalog
) -> tuple[str, ...]:
    """Return contract violations without opening a warehouse or database."""
    raw_nodes = manifest.get("nodes")
    if not isinstance(raw_nodes, Mapping):
        return ("manifest.nodes must be a mapping",)

    expected_relations = set(catalog.models_by_relation)
    dbt_relations: dict[str, list[tuple[str, str]]] = defaultdict(list)
    failures: list[str] = []
    gold_schema = catalog.gold_schema.casefold()

    for unique_id, raw_node in raw_nodes.items():
        if not isinstance(raw_node, Mapping) or raw_node.get("resource_type") != "model":
            continue

        schema = raw_node.get("schema")
        if not isinstance(schema, str) or schema.casefold() != gold_schema:
            continue

        name = raw_node.get("name")
        alias = raw_node.get("alias")
        relation_name = alias if isinstance(alias, str) and alias.strip() else name
        if not isinstance(relation_name, str) or not relation_name.strip():
            failures.append(f"Gold model {unique_id!r} has no usable name or alias")
            continue

        relation = f"{schema}.{relation_name}".casefold()
        config = raw_node.get("config")
        materialized = config.get("materialized") if isinstance(config, Mapping) else None
        if not isinstance(materialized, str) or materialized.casefold() == "ephemeral":
            failures.append(
                f"{relation} must be a queryable dbt model, got materialized={materialized!r}"
            )
        dbt_relations[relation].append((str(unique_id), str(materialized)))

    for relation, nodes in sorted(dbt_relations.items()):
        if len(nodes) > 1:
            ids = ", ".join(unique_id for unique_id, _ in nodes)
            failures.append(f"dbt manifest has duplicate Gold relation {relation}: {ids}")

    dbt_relation_set = set(dbt_relations)
    missing_from_dbt = sorted(expected_relations - dbt_relation_set)
    missing_from_catalog = sorted(dbt_relation_set - expected_relations)
    if missing_from_dbt:
        failures.append("catalog relations absent from dbt Gold graph: " + ", ".join(missing_from_dbt))
    if missing_from_catalog:
        failures.append("dbt Gold relations absent from semantic catalog: " + ", ".join(missing_from_catalog))

    return tuple(failures)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Verify that dbt Gold relations match the Text-to-SQL catalog."
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("ecom_analytics/target/manifest.json"),
        help="Path to the dbt manifest generated by dbt parse.",
    )
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    try:
        with args.manifest.open("r", encoding="utf-8") as manifest_file:
            manifest = json.load(manifest_file)
        if not isinstance(manifest, Mapping):
            raise DbtCatalogContractError("dbt manifest root must be a JSON object")
        config = load_config()
    except (OSError, json.JSONDecodeError, CatalogConfigError, DbtCatalogContractError) as exc:
        print(f"FAIL dbt/catalog contract: {exc}")
        return 1

    failures = validate_dbt_manifest(manifest, config.catalog)
    if failures:
        print("FAIL dbt/catalog contract:")
        for failure in failures:
            print(f"- {failure}")
        return 1

    relation_count = len(config.catalog.models_by_relation)
    print(
        f"PASS dbt/catalog contract: {relation_count} Gold relations match; "
        "all are queryable models."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
